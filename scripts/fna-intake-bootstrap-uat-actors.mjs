#!/usr/bin/env node
/**
 * Bootstrap dedicated FNA intake UAT client + adviser with known passwords.
 * Writes e2e/.env.local (gitignored).
 *
 * Usage: node scripts/fna-intake-bootstrap-uat-actors.mjs
 */

import { createClient } from '@supabase/supabase-js';
import { execSync } from 'node:child_process';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const PROJECT_REF = 'vpjmdsltwrnpefzcgdmz';
const SUPABASE_URL = `https://${PROJECT_REF}.supabase.co`;

const CLIENT_EMAIL = 'fna-intake-uat-client@navigatewealth.co';
const ADVISER_EMAIL = 'fna-intake-uat-adviser@navigatewealth.co';
const UAT_PASSWORD = 'FnaUat!2026Secure';

function getServiceRoleKey() {
  if (process.env.SUPABASE_SERVICE_ROLE_KEY) {
    return process.env.SUPABASE_SERVICE_ROLE_KEY;
  }
  const out = execSync(`npx supabase projects api-keys --project-ref ${PROJECT_REF} -o json`, {
    encoding: 'utf8',
    cwd: resolve(__dirname, '..'),
  });
  const rows = JSON.parse(out);
  const row = rows.find((r) => r.name === 'service_role');
  if (!row?.api_key) {
    throw new Error('Could not resolve service_role key from Supabase CLI');
  }
  return row.api_key;
}

async function findUserByEmail(supabase, email) {
  let page = 1;
  while (page <= 20) {
    const { data, error } = await supabase.auth.admin.listUsers({ page, perPage: 200 });
    if (error) throw error;
    const match = data.users.find((u) => u.email?.toLowerCase() === email.toLowerCase());
    if (match) return match;
    if (data.users.length < 200) break;
    page += 1;
  }
  return null;
}

async function ensureUser(supabase, { email, password, metadata }) {
  const existing = await findUserByEmail(supabase, email);
  if (existing) {
    const { data, error } = await supabase.auth.admin.updateUserById(existing.id, {
      password,
      email_confirm: true,
      user_metadata: { ...existing.user_metadata, ...metadata },
    });
    if (error) throw error;
    return data.user;
  }

  const { data, error } = await supabase.auth.admin.createUser({
    email,
    password,
    email_confirm: true,
    user_metadata: metadata,
  });
  if (error) throw error;
  return data.user;
}

async function upsertKv(supabase, key, value) {
  const { error } = await supabase
    .from('kv_store_91ed8379')
    .upsert({ key, value }, { onConflict: 'key' });
  if (error) throw error;
}

async function main() {
  const serviceKey = getServiceRoleKey();
  const supabase = createClient(SUPABASE_URL, serviceKey, {
    auth: { persistSession: false, autoRefreshToken: false },
  });

  const adviser = await ensureUser(supabase, {
    email: ADVISER_EMAIL,
    password: UAT_PASSWORD,
    metadata: {
      firstName: 'FNA',
      lastName: 'UAT Adviser',
      role: 'adviser',
      invited: true,
      mustSetPassword: false,
      createdByAdmin: true,
    },
  });

  await upsertKv(supabase, `personnel:profile:${adviser.id}`, {
    id: adviser.id,
    email: ADVISER_EMAIL,
    firstName: 'FNA',
    lastName: 'UAT Adviser',
    role: 'adviser',
    status: 'active',
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
  });

  const client = await ensureUser(supabase, {
    email: CLIENT_EMAIL,
    password: UAT_PASSWORD,
    metadata: {
      firstName: 'FNA',
      surname: 'UAT Client',
      fullName: 'FNA UAT Client',
      role: 'client',
      accountType: 'Personal Client',
      accountStatus: 'approved',
      origin: 'admin_import',
      mustSetPassword: false,
      mustAcceptTerms: false,
    },
  });

  const applicationId = `fna-uat-app-${client.id.slice(0, 8)}`;
  await upsertKv(supabase, `application:${applicationId}`, {
    id: applicationId,
    userId: client.id,
    status: 'approved',
    adviserId: adviser.id,
    approvedBy: adviser.id,
    origin: 'admin_import',
    updatedAt: new Date().toISOString(),
  });

  await upsertKv(supabase, `user_profile:${client.id}:personal_info`, {
    profileType: 'personal',
    userId: client.id,
    email: CLIENT_EMAIL,
    firstName: 'FNA',
    surname: 'UAT Client',
    role: 'client',
    accountStatus: 'approved',
    applicationId,
    adviserId: adviser.id,
    updatedAt: new Date().toISOString(),
  });

  const envPath = resolve(__dirname, '../e2e/.env.local');
  mkdirSync(dirname(envPath), { recursive: true });
  const envContent = `# Auto-generated by scripts/fna-intake-bootstrap-uat-actors.mjs — do not commit
PLAYWRIGHT_BASE_URL=http://localhost:3000
E2E_FNA_CLIENT_EMAIL=${CLIENT_EMAIL}
E2E_FNA_CLIENT_PASSWORD=${UAT_PASSWORD}
E2E_FNA_ADVISER_EMAIL=${ADVISER_EMAIL}
E2E_FNA_ADVISER_PASSWORD=${UAT_PASSWORD}
E2E_FNA_CLIENT_ID=${client.id}
E2E_FNA_ADVISER_ID=${adviser.id}
`;
  writeFileSync(envPath, envContent, 'utf8');

  console.log('FNA UAT actors ready');
  console.log(`  client:  ${CLIENT_EMAIL} (${client.id})`);
  console.log(`  adviser: ${ADVISER_EMAIL} (${adviser.id})`);
  console.log(`  wrote:   ${envPath}`);
}

main().catch((err) => {
  console.error(err.message || err);
  process.exit(1);
});
