import { useQuery, useQueryClient } from '@tanstack/react-query';
import { useCallback } from 'react';
import { communicationApi } from '../../../communication';
import { NEWSLETTER_GROUP_ID } from './groupModel';

export const clientGroupKeys = {
  all: ['client-management', 'groups'] as const,
  list: () => [...clientGroupKeys.all, 'list'] as const,
  clients: () => [...clientGroupKeys.all, 'clients'] as const,
  providers: () => [...clientGroupKeys.all, 'providers'] as const,
};

/**
 * Groups shown in Client Management › Groups: custom groups, the newsletter
 * system group (editable external contacts) and auto-generated provider
 * groups (read-only, visible so they can be used).
 */
export function useClientGroups() {
  const queryClient = useQueryClient();
  const groupsQuery = useQuery({
    queryKey: clientGroupKeys.list(),
    queryFn: async () => {
      const groups = await communicationApi.getGroups();
      return groups.filter(
        (g) => !g.type || g.type === 'custom' || g.id === NEWSLETTER_GROUP_ID || g.autoGenerated,
      );
    },
  });
  const refresh = useCallback(
    () => queryClient.invalidateQueries({ queryKey: clientGroupKeys.list() }),
    [queryClient],
  );
  return {
    groups: groupsQuery.data ?? [],
    loading: groupsQuery.isLoading,
    error: groupsQuery.error,
    refresh,
  };
}

/** Clients and providers the group editor needs (manual selection, product rules). */
export function useGroupEditorOptions() {
  const clientsQuery = useQuery({
    queryKey: clientGroupKeys.clients(),
    queryFn: () => communicationApi.getClients(),
  });
  const providersQuery = useQuery({
    queryKey: clientGroupKeys.providers(),
    queryFn: () => communicationApi.getProviders(),
  });
  return {
    clients: clientsQuery.data ?? [],
    providers: providersQuery.data ?? [],
    loading: clientsQuery.isLoading || providersQuery.isLoading,
  };
}
