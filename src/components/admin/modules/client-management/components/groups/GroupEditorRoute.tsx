import { ChevronLeft } from 'lucide-react';
import { Button } from '../../../../../ui/button';
import { ErrorState } from '../../../../layout/page';
import { GroupEditorPage } from './GroupEditorPage';
import { useClientGroups } from './useClientGroups';

interface GroupEditorRouteProps {
  /** The ?group= value: a group id, or 'new'. */
  groupId: string;
  onClose: () => void;
}

/** Resolves ?group=<id|new> to the editor page, with loading and not-found states. */
export function GroupEditorRoute({ groupId, onClose }: GroupEditorRouteProps) {
  const { groups, loading, error, refresh } = useClientGroups();

  if (groupId === 'new') {
    return <GroupEditorPage group={null} onClose={onClose} onChanged={refresh} />;
  }

  if (loading) {
    return (
      <div className="flex flex-col gap-4" aria-busy="true">
        <div className="h-5 w-24 animate-pulse rounded bg-muted" />
        <div className="h-8 w-72 animate-pulse rounded bg-muted" />
        <div className="h-40 animate-pulse rounded-xl bg-muted/70" />
      </div>
    );
  }

  const group = groups.find((g) => g.id === groupId);
  if (!group || group.autoGenerated) {
    return (
      <div className="flex flex-col gap-4">
        <button
          type="button"
          onClick={onClose}
          className="inline-flex w-fit items-center gap-1 rounded text-sm text-nw-text-2 hover:text-nw-ink"
        >
          <ChevronLeft className="h-4 w-4" aria-hidden="true" />
          Groups
        </button>
        <ErrorState
          title={error ? 'Could not load groups' : 'This group could not be opened'}
          description={
            error
              ? 'Something went wrong while loading. Nothing you entered was lost.'
              : 'It may have been deleted, or the link may be wrong.'
          }
          onRetry={error ? () => void refresh() : undefined}
          secondaryAction={
            <Button variant="outline" onClick={onClose}>
              Back to groups
            </Button>
          }
        />
      </div>
    );
  }

  return <GroupEditorPage key={group.id} group={group} onClose={onClose} onChanged={refresh} />;
}
