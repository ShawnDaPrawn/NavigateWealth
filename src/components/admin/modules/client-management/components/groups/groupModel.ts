/** Same rules as the old manager's type filter and sort. */
export function filterAndSortGroups(
  groups: ClientGroup[],
  { search, type, sort }: { search: string; type: GroupTypeFilter; sort: GroupSort },
): ClientGroup[] {
  let result = [...groups];
  if (search) {
    const lower = search.toLowerCase();
    result = result.filter(
      (g) => g.name.toLowerCase().includes(lower) || g.description?.toLowerCase().includes(lower),
    );
  }
  if (type === 'with-filters') {
    result = result.filter((g) => hasDynamicFilters(g.filterConfig));
  } else if (type === 'manual-only') {
    result = result.filter(
      (g) =>
        g.clientIds &&
        g.clientIds.length > 0 &&
        (!g.filterConfig || Object.keys(g.filterConfig).length === 0),
    );
  }
  result.sort((a, b) => {
    if (sort === 'name') return a.name.localeCompare(b.name);
    if (sort === 'members') return (b.clientCount || 0) - (a.clientCount || 0);
    const aDate = new Date(a.updatedAt || a.createdAt || 0).getTime();
    const bDate = new Date(b.updatedAt || b.createdAt || 0).getTime();
    return bDate - aDate;
  });
  return result;
}

export function formatGroupDate(value?: Date | string): string {
  if (!value) return '—';
  return new Date(value).toLocaleDateString('en-ZA', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
  });
}

const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
export function isValidEmail(email: string): boolean {
  return EMAIL_RE.test(email.trim());
}

