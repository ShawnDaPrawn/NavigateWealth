/** Whether any dynamic rule is set (empty arrays do not count). */
export function hasDynamicFilters(config?: GroupFilterConfig): boolean {
  if (!config) return false;
  return Object.values(config).some((v) => (Array.isArray(v) ? v.length > 0 : v === true));
}

/** The labels of the rules a group uses, for the list's summary line. */
export function activeFilterLabels(config?: GroupFilterConfig): string[] {
  if (!config) return [];
  const labels: string[] = [];
  if (config.productFilters?.length) labels.push('Products');
  if (config.netWorthFilters?.length) labels.push('Net worth');
  if (config.ageFilters?.length) labels.push('Age');
  if (config.maritalStatusFilters?.length) labels.push('Marital status');
  if (config.employmentStatusFilters?.length) labels.push('Employment');
  if (config.genderFilters?.length) labels.push('Gender');
  if (config.countryFilters?.length) labels.push('Country');
  if (config.incomeFilters?.length) labels.push('Income');
  if (config.occupationFilters?.length) labels.push('Occupation');
  if (config.dependantCountFilters?.length) labels.push('Dependants');
  if (config.retirementAgeFilters?.length) labels.push('Retirement age');
  return labels;
}

export function groupKind(group: ClientGroup): 'auto' | 'system' | 'dynamic' | 'manual' {
  if (group.autoGenerated) return 'auto';
  if (group.type === 'system') return 'system';
  return hasDynamicFilters(group.filterConfig) ? 'dynamic' : 'manual';
}

