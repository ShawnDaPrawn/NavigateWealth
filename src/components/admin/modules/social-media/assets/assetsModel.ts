// Settings dialog form <-> API patch
// ---------------------------------------------------------------------------

export interface SettingsFormState {
  enabled: boolean;
  assets_per_channel: string;
  posts_per_channel_per_week: string;
  channels: SocialChannel[];
  posting_timezone: string;
  site_origin: string;
  slots: Record<SocialChannel, string>;
  style_guide: string;
  compliance_rules: string;
}

export function settingsToForm(settings?: SocialAutomationSettings): SettingsFormState {
  return {
    enabled: settings?.enabled ?? true,
    assets_per_channel: String(settings?.assets_per_channel ?? 5),
    posts_per_channel_per_week: String(settings?.posts_per_channel_per_week ?? 2),
    channels: settings?.channels ?? [...CHANNEL_ORDER],
    posting_timezone: settings?.posting_timezone ?? 'Africa/Johannesburg',
    site_origin: settings?.site_origin ?? '',
    slots: {
      linkedin: slotsToText(settings?.preferred_slots?.linkedin),
      instagram: slotsToText(settings?.preferred_slots?.instagram),
      x: slotsToText(settings?.preferred_slots?.x),
    },
    style_guide: settings?.style_guide ?? '',
    compliance_rules: settings?.compliance_rules ?? '',
  };
}

/** Validate and translate the form into the API patch, or explain what is wrong. */
export function formToPatch(form: SettingsFormState): {
  patch?: SocialAutomationSettingsPatch;
  error?: string;
} {
  const assetsPerChannel = Number(form.assets_per_channel);
  const postsPerWeek = Number(form.posts_per_channel_per_week);
  if (!Number.isInteger(assetsPerChannel) || assetsPerChannel < 1 || assetsPerChannel > 20) {
    return { error: 'Assets per channel must be a whole number between 1 and 20.' };
  }
  if (!Number.isInteger(postsPerWeek) || postsPerWeek < 0 || postsPerWeek > 7) {
    return { error: 'Posts per channel per week must be a whole number between 0 and 7.' };
  }
  if (form.channels.length === 0) return { error: 'Choose at least one channel.' };
  if (!/^https?:\/\/.+/.test(form.site_origin.trim())) {
    return { error: 'Site origin must be a full URL, e.g. https://www.navigatewealth.co' };
  }
  const preferred_slots: Record<string, string[]> = {};
  for (const channel of CHANNEL_ORDER) {
    const { slots, invalid } = parseSlotsText(form.slots[channel]);
    if (invalid) {
      return {
        error: `${CHANNEL_LABEL[channel]} slot "${invalid}" is not "dow HH:MM" (e.g. tue 07:30).`,
      };
    }
    preferred_slots[channel] = slots;
  }
  return {
    patch: {
      enabled: form.enabled,
      assets_per_channel: assetsPerChannel,
      posts_per_channel_per_week: postsPerWeek,
      channels: form.channels,
      posting_timezone: form.posting_timezone.trim(),
      site_origin: form.site_origin.trim(),
      preferred_slots,
      style_guide: form.style_guide,
      compliance_rules: form.compliance_rules,
    },
  };
}
